import { createHash } from "node:crypto";
import { existsSync, promises as fs } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outputPath = path.join(root, "docs", "llm-context.md");
const checkOnly = process.argv.includes("--check");

const canonicalDocs = [
  "README.md",
  "agent.md",
  "architecture.md",
  "developer.md",
  "changelogs.md",
  "docs/api-map.md",
  "docs/implementation-status.md",
];

const inventoryRoots = [
  ".github/workflows",
  "e2e",
  "scripts",
  "src/app/api",
  "src/app/components/auth",
  "src/app/components/charts",
  "src/app/components/feedback",
  "src/app/components/layout",
  "src/app/components/primitives",
  "src/app/components/screens",
  "src/app/context",
  "src/app/lib",
  "src/assets",
  "src/styles",
  "src/test",
];

const inventoryFiles = [
  ".gitignore",
  "eslint.config.js",
  "index.html",
  "package-lock.json",
  "package.json",
  "playwright.config.ts",
  "pnpm-workspace.yaml",
  "postcss.config.mjs",
  "src/app/App.tsx",
  "src/app/components/ui/utils.ts",
  "src/app/routes.test.tsx",
  "src/app/routes.tsx",
  "src/main.tsx",
  "tsconfig.json",
  "vite.config.ts",
  "vitest.config.ts",
];

async function walk(relativePath) {
  const absolutePath = path.join(root, relativePath);
  if (!existsSync(absolutePath)) return [];
  const entries = await fs.readdir(absolutePath, { withFileTypes: true });
  const files = [];
  for (const entry of entries.sort((a, b) => a.name.localeCompare(b.name))) {
    const child = path.posix.join(relativePath.replaceAll(path.sep, "/"), entry.name);
    if (entry.isDirectory()) files.push(...await walk(child));
    if (entry.isFile()) files.push(child);
  }
  return files;
}

const packageJson = JSON.parse(await fs.readFile(path.join(root, "package.json"), "utf8"));
const inventory = [
  ...(await Promise.all(inventoryRoots.map(walk))).flat(),
  ...inventoryFiles.filter((relativePath) => existsSync(path.join(root, relativePath))),
].sort();
const sourceDigest = createHash("sha256")
  .update(
    (
      await Promise.all(
        inventory.map(async (relativePath) => {
          const content = await fs.readFile(path.join(root, relativePath));
          return `${relativePath}\0${createHash("sha256").update(content).digest("hex")}`;
        }),
      )
    ).join("\n"),
  )
  .digest("hex");

const sections = [
  "# Paiziq Dashboard — Generated LLM Context",
  "",
  "> Generated by `npm run docs:context`; do not edit this file by hand.",
  "> CI runs `npm run docs:check` and fails when this snapshot is stale.",
  "",
  "## Verification commands",
  "",
  "```json",
  JSON.stringify(packageJson.scripts, null, 2),
  "```",
  "",
  "## Implementation inventory",
  "",
  `Source digest: \`${sourceDigest}\``,
  "",
  ...inventory.map((relativePath) => `- \`${relativePath}\``),
  "",
  "## Canonical documentation",
  "",
];

for (const relativePath of canonicalDocs) {
  sections.push(
    `### ${relativePath}`,
    "",
    (await fs.readFile(path.join(root, relativePath), "utf8")).trim(),
    "",
  );
}

const generated = `${sections.join("\n").trim()}\n`;

if (checkOnly) {
  const current = existsSync(outputPath) ? await fs.readFile(outputPath, "utf8") : "";
  if (current !== generated) {
    console.error("docs/llm-context.md is stale; run `npm run docs:context`.");
    process.exitCode = 1;
  } else {
    console.log("docs/llm-context.md is current.");
  }
} else {
  await fs.mkdir(path.dirname(outputPath), { recursive: true });
  await fs.writeFile(outputPath, generated);
  console.log("wrote docs/llm-context.md");
}
